/**
 * Resolves the image URL for a given sub-service object or sub-service ID.
 * Always returns a valid image URL.
 */
export function getSubServiceImage(subService) {
  if (!subService) return '/assets/services/electrical/01_ceiling_fan_switchboard_wiring.jpg';

  // Direct image property on subService object
  if (typeof subService === 'object' && subService.image) {
    return subService.image;
  }

  const subId = typeof subService === 'string' ? subService : subService.id;

  // 1. Check direct ID map
  if (subId && SUB_SERVICE_IMAGE_MAP[subId]) {
    return SUB_SERVICE_IMAGE_MAP[subId];
  }

  // 2. Check keyword match based on English name / translations / description
  const subName = (typeof subService === 'object' ? (subService.name_translations?.en || subService.name || subService.description || '') : '').toLowerCase();
  if (subName) {
    for (const entry of KEYWORD_IMAGE_MAP) {
      if (entry.keywords.some(k => subName.includes(k))) {
        return entry.img;
      }
    }
  }

  return '/assets/services/electrical/01_ceiling_fan_switchboard_wiring.jpg';
}
